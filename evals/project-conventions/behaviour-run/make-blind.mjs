// Builds the blind judging pack from a behavioural run.
//
// Preserved because blinding is the load-bearing part of the protocol: if the pack can leak the
// condition, or if the shuffle is not reproducible, the comparison is not blind and the result is not
// re-derivable. This script is the record of how the pack was made.
//
//   node evals/project-conventions/behaviour-run/make-blind.mjs
//
// Reads results.jsonl and ../../../evals/project-conventions/cases.json, writes blind.jsonl,
// blind-key.jsonl and judgements.md into this directory. The key must never reach a judge.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = dirname(fileURLToPath(import.meta.url));
const CASES = resolve(DIR, '..', 'cases.json');
const suite = JSON.parse(readFileSync(CASES, 'utf8'));
const byId = new Map(suite.cases.map((c) => [c.id, c]));

const rows = readFileSync(join(DIR, 'results.jsonl'), 'utf8')
  .split(/\r?\n/)
  .filter((l) => l.trim())
  .map((l) => JSON.parse(l));

// Fixed seed: a reproducible shuffle, so the pack can be regenerated byte-for-byte and audited.
let seed = 20260924;
const rand = () => {
  seed = (seed * 1103515245 + 12345) % 2147483648;
  return seed / 2147483648;
};
const shuffled = [...rows];
for (let i = shuffled.length - 1; i > 0; i -= 1) {
  const j = Math.floor(rand() * (i + 1));
  [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
}

const pack = shuffled.map((r, i) => ({
  code: `A${String(i + 1).padStart(3, '0')}`,
  case: r.case,
  prompt: byId.get(r.case).prompt,
  answer: r.response,
}));
writeFileSync(join(DIR, 'blind.jsonl'), pack.map((p) => JSON.stringify(p)).join('\n') + '\n');
writeFileSync(
  join(DIR, 'blind-key.jsonl'),
  shuffled
    .map((r, i) =>
      JSON.stringify({
        code: `A${String(i + 1).padStart(3, '0')}`,
        case: r.case,
        condition: r.condition,
        run: r.run,
      }),
    )
    .join('\n') + '\n',
);

const lines = [
  '# Judging pack — project conventions behavioural run',
  '',
  'You are judging answers written by other agents to 20 decision questions about software-project',
  'work. Each answer was produced under one of two conditions, and you are NOT told which. Do not try',
  'to infer it, and do not reward length, confidence, or formal-sounding language.',
  '',
  'For every row in `blind.jsonl` decide **PASS** or **FAIL** against the criterion for its case, and',
  'give a one-line reason. Judge the DECISION and the reason given for it. Where an answer names a',
  'behaviour only to reject it, that is a pass, not a failure.',
  '',
  'Read the full answer. An answer that reaches the right decision for the wrong reason is a FAIL. An',
  'answer that hedges without deciding is a FAIL.',
  '',
  '## Criteria',
  '',
];
for (const c of suite.cases) {
  lines.push(`### ${c.id} (area ${c.area})`, '', `**Question:** ${c.prompt}`, '', `**PASS when:** ${c.rationale}`, '');
}
lines.push(
  '## Output',
  '',
  'Write one JSON object per line, in `blind.jsonl` order, to the output path you were given:',
  '',
  '```json',
  '{"code":"A001","verdict":"PASS","reason":"one line"}',
  '```',
  '',
  'Every row in `blind.jsonl` needs exactly one verdict. Do not skip rows.',
  '',
);
writeFileSync(join(DIR, 'judgements.md'), lines.join('\n'));

console.log(`blind pack: ${pack.length} rows across ${new Set(pack.map((p) => p.case)).size} cases`);
console.log('wrote blind.jsonl, blind-key.jsonl, judgements.md');
